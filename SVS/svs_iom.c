/*
 * КОП командного слова БАКПВВ (база М36, разр.37..44; см. §5.6 и iom-лог).
 * Значения наблюдались в прогоне dispak.ini:
 *   004 — инициализация БАК (указатель на БАКПВВ), обрабатывается через СТБАК;
 *   005/006/007 — регистрация управляющих таблиц ПВВ (адрес в разр.1..36):
 *                 005→УТ (таблица устройств), 006→ТОЧ (очереди), 007→таблица ответов.
 *                 Адреса определены эмпирически: КОП=006 несёт A(ТОЧ)=30540
 *                 (совпадает с АТОЧ из адап.bemsh, D31577).
 *   015 — управляющая команда без адреса;
 *   016 — ПУСКОБ: обойти ТОЧ и выполнить обмен (см. iom_pusk_obmen).
 */
#define BAK_KOP_REG_UT      0005    /* регистрация таблицы устройств  → UTA  */
#define BAK_KOP_REG_TOCH    0006    /* регистрация таблицы очередей ТОЧ → IOQA */
#define BAK_KOP_REG_ANSW    0007    /* регистрация таблицы ответов    → SQA  */
#define BAK_KOP_IBAK        0004    /* ИБАК: регистрация указателя на БАКПВВ    */
#define BAK_KOP_POBR        0012    /* ПОБР: разовый пуск объекта (режим ЦРВ)   */
/* Ячейка слова состояния для ПОБР: её опрашивает ВЫЗПВВ (СЧП '105'). */
#define IOM_POBR_STATUS     0105
#define BAK_KOP_PUSKOB      0016    /* ПУСКОБ: пуск обмена по очереди ТОЧ      */

/*
 * Маска значащего адреса в слове-указателе ТОЧ / звене заявки.
 * Звенья связаны через 0-е слово заявки; в старших разрядах указателя стоит
 * СЕМБИТ (разр.17 = 0o200000, семафорный/занятости бит, адап.bemsh: СЕМБИТ КОНД
 * М16В'1'). Аналог микрокоманды ДАЙМА — выделить адрес, отбросив признаки.
 */
#define IOM_DAIMA(v)        ((uint32)((v) & 077777))   /* разр.1..15: адрес заявки */
#define IOM_SEMBIT          000200000LL                /* разр.17: СЕМБИТ */

/*
 * ТВЗП — таблица заявок, отданных СВС (per-СВС), куда ВКЛТОЧ кладёт заявку по
 * ветви ОТДАЮЗ (НУС=0): СЧИМ АЗАЯВ; ИЛИ СЕМБИТ; ЗПП (НСВС) (адап.bemsh:3680).
 * В конфигурации dispak.ini (НАПРУС=0, один СВС, НСВС=0) слот ТВЗП[0] оказывается
 * по физическому адресу 030540+... — определён эмпирически как 031270. Это не
 * зарегистрированная каналом структура, поэтому адрес зашит здесь как константа
 * (TODO: получать ТВЗП из таблицы устройств или регистрировать командой БАК).
 */
#define IOM_TVZP            031270      /* ТВЗП[НСВС=0]: слот отданной заявки */

/*
 * НАПРУС — параметр "направление и номер устройства системного диска"
 * (адап.bemsh), задаётся снаружи (в dispak.ini: `d 30115 <n>`) и читается
 * ADAP-ом при выдаче заявок на системный диск по ветви ОТДАЮЗ (НУС=0). Канал
 * должен обслуживать ту же заявку, на то же устройство, какое указано ЗДЕСЬ —
 * не константой в C, а тем же словом, которое сконфигурировал dispak.ini/сам
 * АДАП, иначе dev в svs_disk_io() и НУС в ответе ДР разойдутся с тем, что
 * ожидает остальной код АДАП-а (ГАСИПР/ВЫППВВ/ИНДБУД).
 */
#define IOM_NAPRUS           030115

/*
 * ДВРПВВ — голова очереди завершённых заявок ПВВ, которую ГАСИПР (адап.bemsh,
 * обработчик ПРПВВ) читает через ДВРОС := ДВРПВВ (см. ЗППР ДВРОС в ППВВ).
 * Адрес НЕ зашит в эмуляторе: это ровно та "таблица ответов", которую сам
 * АДАП регистрирует командой БАК КОП=007 (BAK_KOP_REG_ANSW) — см. обработчик
 * ниже, кладущий её в iom->SQA. В конфигурации dispak.ini регистрируется
 * ОТВ@031350, что совпадает с символом ДВРПВВ из адап.bemsh.
 * Слово хранится как (значение48<<16)|мл16 (аппаратный тег — отдельно в tag[]):
 *   значение48, разр.17..36 (после СЧП ДВРОС; СДА 64+17; И =Х'FFFFF') — АН:
 *     ЛИБО ноль, ЛИБО ненулевое значение, равное (z-ПВВ) — адресу заявки z,
 *     взятому ОТНОСИТЕЛЬНО ПВВ и сдвинутому на 17 влево. Ветка АНДВР сразу
 *     после этого делает "ДМА" == "ВЧ АДРЕС" (адап.bemsh), т.е. АДР :=
 *     АН - память[АДРЕС], а память[АДРЕС] в этой конфигурации хранит -ПВВ,
 *     так что АДР получается уже АБСОЛЮТНЫМ (=z) — именно с ним ГАСИПР потом
 *     сверяется на границы/кратность 8. Отсюда: значение48 = (z-ПВВ)<<17,
 *     НЕ z<<17 — если положить туда голый z, АДР на выходе окажется z+ПВВ.
 *     (Если АН=0, читается мл16: мл16=0 -> ДВРПУС/ВЫХПРВ, пусто; мл16≠0
 *     без АН — ошибка ОШДВР "АН=0,АК" в адап.bemsh, поэтому АН должен быть
 *     ненулевым всегда, когда мы связываем реальную заявку.)
 *   мл16 — тот же адрес, извлекаемый макросом ДАЙМА (СЧМР; СДА 64+32; ВЧ ПМА)
 *     в АКБВВ для сверки с АНБВВ=z в АКТИВ. ДАЙМА вычитает СОДЕРЖИМОЕ ПМА
 *     (≡ ячейка АДРЕС = база переноса), поэтому мл16 = z_virt + база —
 *     см. iom_xfer_zaiavka.
 * Одна запись — одна заявка (сл.0 самой заявки, т.е. связь на следующую,
 * не трогается: ADAP оставляет её нулевой/самозамкнутой для одиночной
 * заявки, поддержка цепочки из нескольких одновременных завершений через
 * ТОЧ пока не реализована).
 */
#define IOM_PVV_BASE        030000      /* ПВВ: вирт. база модуля АДАП */
#define IOM_AKTZ            04000000    /* АКТЗ (М20В'1'): признак "активная заявка" в сл.7 заявки */

/*
 * НУС — индекс записи устройства в параллельных таблицах ТУСЗ(030200) и
 * ТУС(030360); обе по 0160 слов (112), разбиты на блоки по 16 записей на класс
 * устройства. Блок МД (класс 5) начинается со смещения 0120: ТУС 030500-030517,
 * ТУСЗ 030320-030337 (проверено дампом в точке ИНДБУД, см. dispak.ini).
 */
#define IOM_TUS_ENTRIES     0160        /* записей в ТУС/ТУСЗ (7 классов по 16) */
#define IOM_ZONE_SERVICE    8           /* служебных слов в зоне */
#define IOM_TUS_CLASS_MB    4           /* класс МБ (барабан): ТУСМБ@030460, канал Х'20' */
#define IOM_TUS_CLASS_MD    5           /* класс МД (диск):    ТУСМД@030500, канал Х'22' */
#define IOM_TUS_CLASS_ACPU  0100        /* АЦПУ: не блок ТУС, узнаётся по каналу */
#define IOM_ACPU_CHANNEL    4           /* канал АЦПУ0 (ТУС 017); АЦПУ1 — Х'5' (ТУС 077) */
#define IOM_TUS_CLASS_PK    0101        /* считыватель перфокарт: ПК0 (ТУС 014), ПК1 (074) */
#define IOM_TUS_CLASS_FS    0102        /* фотосчитыватель ленты: ФС0 (ТУС 010), ФС1 (070) */
#define IOM_ES_CLASS(c)     ((c) >= IOM_TUS_CLASS_ACPU)   /* устройство ЕС-канала */
#define IOM_TUS_BLOCK       020         /* записей в блоке одного класса */

/* Смещение блока класса в ТУС: класс k лежит по k*16 (МБ 4*16=0100, МД 5*16=0120). */
#define IOM_TUS_CLASS_BASE(c)   ((c) * IOM_TUS_BLOCK)
/* Ограничитель обхода очереди ТОЧ — см. цикл в iom_pusk_obmen. */
#define IOM_QUEUE_MAX_STEPS     256
#define IOM_NUS_MD_BASE         IOM_TUS_CLASS_BASE(IOM_TUS_CLASS_MD)

/*
 * Класс устройства и номер внутри класса по индексу НУС.
 *
 * Обе таблицы устройств разбиты на блоки по 16 записей, по блоку на класс, а
 * МЛАДШЕЕ поле записи ТУС несёт номер класса (…0004 у МБ, …0005 у МД —
 * проверено дампом ТУС). Адрес самой ТУС канал не угадывает: его регистрирует
 * команда БАК КОП=005 в iom->UTA (наблюдалось УТ@100360).
 *
 * Возвращает номер класса, либо -1, если ТУС недоступна или запись пуста;
 * в этом случае заявку надо пропустить, а не обслуживать наугад.
 */
static int iom_tus_class(IOMDATA *iom, int nus, int *unit)
{
    uint32 a;
    int cls;

    if (iom->UTA == 0)
        return -1;
    a = iom->UTA + nus;
    if (a >= MEMSIZE)
        return -1;

    /*
     * Устройства ввода тоже вне блоков классов. ФС делит канал с ПЛ
     * (Х'9' и Х'7'), поэтому их узнаём по индексу ТУС (адап.bemsh, ТУС).
     */
    if ((memory[a] >> 16) & BITS48) {
        switch (nus) {
        case 014: *unit = 0; return IOM_TUS_CLASS_PK;
        case 074: *unit = 1; return IOM_TUS_CLASS_PK;
        case 010: *unit = 0; return IOM_TUS_CLASS_FS;
        case 070: *unit = 1; return IOM_TUS_CLASS_FS;
        }
    }

    /*
     * АЦПУ стоят вне блоков классов (ТУС 017 и 077, а младшее поле там —
     * номер блока: 0 и 3, как у соседних МЛ). Узнаём их по номеру канала,
     * разр.33-38 слова ТУС: Х'4' — АЦПУ0, Х'5' — АЦПУ1 (адап.bemsh, БУДКАН).
     */
    cls = (int)((memory[a] >> (16 + 32)) & 077);
    if (cls == IOM_ACPU_CHANNEL || cls == IOM_ACPU_CHANNEL + 1) {
        *unit = cls - IOM_ACPU_CHANNEL;
        return IOM_TUS_CLASS_ACPU;
    }

    cls = (int)((memory[a] >> 16) & 07777);      /* младшее поле записи ТУС */
    if (cls <= 0 || IOM_TUS_CLASS_BASE(cls) > nus)
        return -1;

    *unit = nus - IOM_TUS_CLASS_BASE(cls);
    return cls;
}

/*
 * Проверка адреса, вычисленного из командного слова или из очереди.
 *
 * Слово может оказаться мусорным (БАК ещё не настроен, приписка сменилась,
 * очередь испорчена), а обращение memory[] по такому адресу роняет эмулятор.
 * Поэтому каждый адрес, пришедший ИЗ ПАМЯТИ, проверяется по границе ОЗУ.
 */
static int iom_addr_ok(IOMDATA *iom, const char *what, uint32 addr)
{
    if (addr != 0 && addr < MEMSIZE)
        return 1;

    if (SVS_DEV_TRACE())
        fprintf(sim_deb, "iom%d --- %s: адрес %o вне памяти, команда пропущена\n",
            iom->index, what, addr);
    return 0;
}

/*
 * Выполнить обмен по одной заявке (§5.2/§5.4):
 *   сл.2 ДО — буфер ОП и длина; сл.3 СО — направление (ТЕГ48 чтение = разр.48);
 *   сл.4 СПУ — физический адрес зоны. Ответ устройства — в сл.5/6 (ДР/ДРУ).
 * dev — номер устройства МД (из НАПРУС; здесь 0 = канал 0, устройство 0).
 */
static t_stat iom_xfer_zaiavka(IOMDATA *iom, uint32 z, int devclass, int dev, int nus)
{
    /* Слова данных: (значение48<<16)|мл16; значащие 48 разр. — в СТАРШЕЙ
     * части 64-битного слова, поэтому извлекаем сдвигом вправо на 16
     * (так же показывает их команда `e`). Ср. командные слова БАК, где значащие
     * разряды лежат в МЛАДШЕЙ половине. */
    t_value do_  = (memory[z + 2] >> 16) & BITS48;  /* ДО  */
    t_value so   = (memory[z + 3] >> 16) & BITS48;  /* СО  */
    t_value spu  = (memory[z + 4] >> 16) & BITS48;  /* СПУ */
    int is_read  = (int)((so >> 47) & 1);       /* разр.48: ТЕГ48 чтение */
    /*
     * Физический адрес зоны — в РМР слова СПУ (младшие 16 разр. 64-битного слова,
     * §5.4: "копия младших 16 разр. адреса в РМР"). ТУСЗ не настроена → тип ёмкости 0
     * (7,25 МБ) → зона удвоена (зона×2). Диск svs2053.bin — 29 МБ (зона как есть),
     * поэтому делим на 2, восстанавливая логическую зону.
     * TODO: брать тип ёмкости из ТУСЗ[НУС] и масштабировать корректно (§5.4).
     */
    /*
     * Номер зоны — в РМР слова СПУ. Деление пополам — свойство МД (тип ёмкости,
     * зона удвоена); к барабану оно не относится, у него зона берётся как есть.
     */
    int zone     = (int)(memory[z + 4] & 0xFFFF);
    int sector   = 0;
    if (devclass == IOM_TUS_CLASS_MD) {
        /*
         * Делим пополам только при типе ёмкости 7,25 МБ: там АДАП удваивает
         * номер зоны (ветка ДИСК в адап.bemsh, СДА 64-1). При 29 МБ номер
         * настоящий — так его шлёт ВЫЗПВВ (зона 0747 у АДАП-а).
         * Переключается командой `set DISKn 29MB` / `set DISKn 7MB`.
         */
        if (svs_disk_zone_scale(dev) == 2)
            zone >>= 1;
    } else if (devclass == IOM_TUS_CLASS_MB) {
        /*
         * Барабан: АДАП кладёт в РМР слова СПУ не номер зоны, а физический
         * адрес = зона*32 + сектор*8. Видно прямо в адап.bemsh (ветка МБ):
         *   МБ:    СЧМР / СДА 64-2          остаток ДАЙНБ (зона) * 4
         *          СЧМ СМ                   ... в стек
         *   ОБСЕК: И =В'3' / СЛЦ -2(S)      + номер абзаца (0-3)
         *          СДА 64-3                 всё * 8  => зона*32 + сектор*8
         *   НПР:   СДА 64+16 В МР           младшие 16 разр. -> РМР
         * Без деления номера зоны раздувало в 32 раза: файл барабана рос
         * разреженным до сотен мегабайт, а зоны 022300/026400/026440 из
         * трассы — это зоны 294/360/361, идущие подряд.
         */
        sector = (zone >> 3) & 3;
        zone >>= 5;
    }
    /*
     * Адрес буфера — в РМР (младшие 16 разр. 64-битной ячейки) слова ДО, как и
     * номер зоны в СПУ (§5.4), а НЕ в значащих 48 разрядах: там лежит длина.
     * Наблюдалось ДО=0000000000142016 (РМР 002360), где значение48 =
     * (0o1420<<6)|0o16 — то же поле длины, что в константе ДОМЛМД@032140
     * (М22В'1420'В'360'), а 02360 — адрес, по которому РАСПАК и читает зону.
     *
     * Адрес ФИЗИЧЕСКИЙ (лист*1024): см. mmu_iom_data_pa()
     * при каждом обращении (svs_disk.c). Упакованная зона — 8 служебных слов
     * плюс 768 слов данных = 776 слов (0o1410), меньше страницы, и 02360+0o1410
     * = 03770 целиком помещается в вирт. странице 1 (→ физ. 0o1601 по RPS0).
     */
    /*
     * НАМ — начальный адрес массива, разр.0..19 слова ДО (№10.170.002 ТОП,
     * 4.1.5), то есть ДВАДЦАТЬ разрядов, а не шестнадцать.
     *
     * Это ровно младшие 20 разр. 64-битной ячейки, потому что АДАП кладёт ДО
     * так: «СЧИ 8 НОМЕР ЛИСТА / СДА 64-10 АДРЕС / … / ЗАПДО: СДА 64+16;
     * ЗПП 2(АЗАЯВ)». Сдвиг вправо на 16 уводит младшие 16 разр. в РМР, а ЗПП
     * складывает обратно (значение48<<16)|РМР — в ячейке лежит исходная
     * величина целиком. Прежняя маска 0xFFFF брала только РМР и обрезала бы
     * буфер с адресом ≥ 0200000; разр.16-19 берутся из младших разрядов
     * значения48. Поле РАЗМ (разр.22-41) выше и в маску не попадает.
     */
    int memaddr  = (int)(memory[z + 2] & 0xFFFFF);
    /*
     * РАЗМ — размер массива в словах, разр.22..41 слова ДО (4.1.5).
     * Раньше канал его игнорировал и всегда переносил целую зону. Пока ОС
     * просила полную зону (МД 784, МБ 1024) это совпадало, но заявка на
     * 8 слов (чтение одних служебных слов зоны) вываливала в память лишние
     * 768 слов: они ложились нулями с тегом команды на 050..01447, управление
     * проходило сквозь них и падало по контролю команды на 01450.
     */
    int nwords   = (int)((memory[z + 2] >> 22) & 0xFFFFF);
    t_stat r;

    /*
     * ВРЕМЕННАЯ ДИАГНОСТИКА зацикливания. Загрузка бесконечно перечитывает одну
     * и ту же зону в тот же буфер (наблюдалось 2,6 млн чтений зоны 0462).
     * Журнала заявок для разбора мало: все обмены выдаются из одной точки
     * АДАП-а (PC=34377), кто заказчик — не видно. Поэтому ловим момент, когда
     * заявка повторилась N раз подряд, и включаем ПОКОМАНДНУЮ трассу ровно на
     * две итерации: этого хватает, чтобы увидеть тело цикла, и трасса остаётся
     * маленькой.
     */
    {
        static int last_dev = -1, last_zone = -1, last_addr = -1, same = 0;

        if (sim_deb && dev == last_dev && zone == last_zone && memaddr == last_addr) {
            same++;
            if (same == 200) {
                fprintf(sim_deb, "iom%d === заявка повторилась %d раз —"
                    " включаю покомандную трассу на 2 итерации\n", iom->index, same);
                cpu_dev[0].dctrl |= DEB_INSN;
            } else if (same == 202) {
                fprintf(sim_deb, "iom%d === хватит\n", iom->index);
                cpu_dev[0].dctrl &= ~DEB_INSN;
            }
        } else {
            same = 0;
            last_dev = dev; last_zone = zone; last_addr = memaddr;
        }
    }

    if (SVS_DEV_TRACE()) {
        /*
         * Барабаны — группа из 16 устройств 010-027 по 040 зон; сквозной
         * номер зоны печатаем как «устройство/зона в нём».
         */
        char zbuf[32];

        if (devclass == IOM_TUS_CLASS_ACPU)
            snprintf(zbuf, sizeof(zbuf), "АЦПУ%d КОП=%02X", dev, (int)((spu >> 30) & 0xFF));
        else if (devclass == IOM_TUS_CLASS_PK)
            snprintf(zbuf, sizeof(zbuf), "ПК%d КОП=%02X", dev, (int)((spu >> 30) & 0xFF));
        else if (devclass == IOM_TUS_CLASS_FS)
            snprintf(zbuf, sizeof(zbuf), "ФС%d КОП=%02X", dev, (int)((spu >> 30) & 0xFF));
        else if (devclass == IOM_TUS_CLASS_MB)
            snprintf(zbuf, sizeof(zbuf), "%02o/%02o", 010 + zone / 040, zone % 040);
        else
            snprintf(zbuf, sizeof(zbuf), "%o", zone);
        fprintf(sim_deb,
            "iom%d --- обмен: устр=%d(напр %d/устр %d) заявка@%o %s"
            " зона=%s сектор=%d буфер=%o PC=%05o\n"
            "iom%d ---   ДО=%016jo(НАМ %07o РАЗМ %d) СО=%016jo СПУ=%016jo(РМР %06o)\n",
            iom->index, dev,
            (devclass == IOM_TUS_CLASS_MD) ? svs_disk_napr(dev) : 0,
            (devclass == IOM_TUS_CLASS_MD) ? dev % 8 : dev,
            z, is_read ? "ЧТ" : "ЗП", zbuf, sector, memaddr,
            cpu_core[0].PC,
            iom->index, (uintmax_t)do_, (unsigned)(memory[z+2] & 0xFFFFF),
            (unsigned)((memory[z+2] >> 22) & 0xFFFFF),
            (uintmax_t)so, (uintmax_t)spu, (unsigned)(memory[z+4] & 0xFFFF));
    }

    /* Зона = 8 служебных слов (в буфер) + 1024 слова данных (буфер+8). */
    /*
     * Раскладка зоны в памяти (проверено по РАСПАК): база из ДО, всего
     * 0o1420 = 784 слова — столько же, сколько в поле длины ДОМЛМД@032140
     * (М22В'1420'). Служебные слова идут с базы, а 768 слов упакованных
     * данных — с базы+16: РАСПАК читает их циклом с 02400 по 03777
     * (034716: УИА -767(3); 034717: СЧ 3777(3)), то есть последние 768 слов
     * страницы. При базе 02360 это ровно база+16.
     */
    /*
     * ДИАГНОСТИКА: не затирает ли обмен служебные структуры АДАП-а?
     * Гипотеза: образ ОС, читаемый ЧТГП на страницы 11-30, ложится поверх
     * области АДАП-а, и после этого канал читает в БАКПВВ мусор. Проверяем
     * ФИЗИЧЕСКИЕ адреса приёмника против зарегистрированных таблиц.
     */
    if (SVS_DEV_TRACE() && !is_read) {
        /* запись на устройство память не портит — проверяем только чтение */
    } else if (SVS_DEV_TRACE()) {
        static const char *what[] = { "БАКПВВ", "ТУС", "ТОЧ", "ДВРПВВ" };
        uint32 cell[4];
        int w, k;

        cell[0] = iom->BAK;  cell[1] = iom->UTA;
        cell[2] = iom->IOQA; cell[3] = iom->SQA;

        for (w = 0; w < IOM_ZONE_SERVICE + 1024; w++) {
            uint32 pa = mmu_iom_data_pa(memaddr + w);

            for (k = 0; k < 4; k++) {
                if (cell[k] != 0 && pa == cell[k]) {
                    fprintf(sim_deb, "iom%d --- !!! ЧТЕНИЕ ЗАТРЁТ %s@%o:"
                        " слово %d буфера %o (вирт.%o) ложится туда же\n",
                        iom->index, what[k], cell[k], w, memaddr, memaddr + w);
                    cell[k] = 0;        /* сообщаем один раз на обмен */
                }
            }
        }
    }

    switch (devclass) {
    case IOM_TUS_CLASS_MD:
        r = svs_disk_io(dev, zone, memaddr, memaddr + 16, !is_read, nwords);
        break;
    case IOM_TUS_CLASS_MB:
        /*
         * Барабан: слова хранятся буквально, без свёртки 4:3, и массив ДО —
         * это ТОЛЬКО данные, начиная прямо с НАМ. Служебные слова зоны АДАП
         * возит отдельной заявкой в СС1Н, в массив обмена они не входят,
         * поэтому сдвигать данные на 8 слов нельзя (это уводило всю страницу).
         */
        r = svs_drum_io(dev, zone, sector, memaddr, !is_read, nwords);
        break;
    case IOM_TUS_CLASS_ACPU:
        /* КОП команды ЕС-канала — разр.31-38 СПУ (ОБЩН в ПВВ.bemsh). */
        r = svs_printer_io(dev, (int)((spu >> 30) & 0xFF), memaddr, nwords);
        break;
    case IOM_TUS_CLASS_PK:
        r = svs_card_io(dev, (int)((spu >> 30) & 0xFF), memaddr, nwords);
        break;
    case IOM_TUS_CLASS_FS:
        r = svs_tape_io(dev, (int)((spu >> 30) & 0xFF), memaddr, nwords);
        break;
    default:
        r = SCPE_NXDEV;
        break;
    }

    if (SVS_DEV_TRACE())
        fprintf(sim_deb, "iom%d ---   %s → %s\n", iom->index,
            (devclass == IOM_TUS_CLASS_MD) ? "svs_disk_io" :
            (devclass == IOM_TUS_CLASS_MB) ? "svs_drum_io" :
            (devclass == IOM_TUS_CLASS_ACPU) ? "svs_printer_io" :
            (devclass == IOM_TUS_CLASS_PK) ? "svs_card_io" :
            (devclass == IOM_TUS_CLASS_FS) ? "svs_tape_io" : "класс не поддержан",
            (r == SCPE_OK) ? "OK" : "ОШИБКА");

    /*
     * Ответ устройства в сл.5/6 (ДР/ДРУ). Как и ДВРПВВ, слово читается через
     * СЧП+СЧМР — значащая часть в мл16, а не в 48-битном значении
     * (см. ВЫППВВ, адап.bemsh:1816-1829):
     *   СЧП 5(АДР); СЧМР; СДА 64+34; И =Х'1777' -> НУС; СДА 64-1 -> НСВС=НУС*2;
     *   ПО ОШДВР2 "ВРЕТ ДРУ", если НУС*2 = 0  -- т.е. НУС обязан быть ненулевым.
     * Следом (32520-32522):
     *   СЧП 4(АДР) СПУ; СДА 64+38 -> ACC=СПУ>>38;
     *   СЧИМ НУС  -- "счим" (case 043, "its"): ТОЛКАЕТ текущий ACC (СПУ>>38) в
     *     стек по M[017] (S), затем грузит ACC:=НУС (обычная семантика счи);
     *   НТЖ (S)   -- (S) с рег.017 — аппаратный POP: снимает то самое СПУ>>38
     *     и делает ACC ^= (СПУ>>38);
     *   И =В'17'; ПЕ ОШДВР2 "ОШИБСЯ ДВР" -- ошибка, если
     *     (НУС ^ (СПУ>>38)) & 017 != 0.
     * Проверено дампом ТУС/ТУСЗ в точке ИНДБУД (см. ПВВ.md §5.3): НУС — это
     * ИНДЕКС ЗАПИСИ в параллельных таблицах ТУСЗ(030200)/ТУС(030360), а не номер
     * устройства на шине. Обе таблицы по 112 слов, разбиты на 7 блоков по 16
     * записей — по блоку на класс устройства, блок класса k лежит по смещению
     * k*020. Диск (МД) — класс 5, смещение 0120 (=ТУСМД в адап.bemsh).
     * Младшие 4 разряда НУС — номер устройства ВНУТРИ класса; ВЫППВВ сверяет их
     * с разр.39-42 слова СПУ, которое строит сам АДАП, поэтому берём их оттуда,
     * а не из НАПРУС/dev. Подтверждено дважды: обе проверки ВЫППВВ проходят
     * (ОШДВР2 не срабатывает), и ИНДБУД находит канал МД (Х'22') в БУДКАН ровно
     * за 18 итераций — по индексу 17, где 0x22 и стоит.
     */
    if (IOM_ES_CLASS(devclass)) {
        /*
         * АЦПУ и устройства ввода стоят вне блоков классов, поэтому НУС в ДР —
         * сам индекс ТУС.
         * Неготовность (файл не подключён, колода или лента кончилась) —
         * состояние устройства, а не сбой канала, и в ДР кроме НУС ничего нет:
         *  - БНС (разр.1) при сброшенном ВУНН (разр.13) АДАП считает сбоем
         *    обмена и сбрасывает ПВВ (ПВВ.bemsh: И ОШДР / НТЖ =В'1' / ПЕ БЕЗОШБ);
         *  - НУС АДАП берёт как (мл16 >> 2) & 01777, то есть разр.3-12, и любой
         *    лишний разряд там уводит ИНДБУД в чужую запись БУДКАН (ОШД12).
         * Состояние — только в ДРУ: «требуется вмешательство оператора»,
         * второй сверху разряд байта уточнённого состояния (разр.47). ДАЙКОТ
         * читает ДРУ всегда; ПЕЧАТЬ проверяет код маской КСБДР, В1К — в РАБВ.
         */
        memory[z + 5] = (t_value)(nus << 2) & 0177777;
        memory[z + 6] = (r == SCPE_OK) ? 0 : ((t_value)1 << 46) << 16;
    } else {
        memory[z + 5] = ((t_value)((r == SCPE_OK) ? 0 : 1) << 16) |
            (((t_value)(IOM_TUS_CLASS_BASE(devclass) + ((spu >> 38) & 017)) << 2) & 0177777);
        memory[z + 6] = 0;
    }

    /*
     * Связываем завершённую заявку с ДВРПВВ, чтобы обработчик ПРПВВ (ГАСИПР)
     * действительно её увидел — см. комментарий о ДВРПВВ/iom->SQA выше. Без этого
     * ГАСИПР читает ДВРОС=0 (пусто) и сразу уходит через ДВРПУС/ВЫХПРВ, не
     * доходя до АКТИВ/ВЫППВВ/РАСПАК.
     */
    if (iom->SQA == 0) {
        /* Таблица ответов не зарегистрирована (не было БАК КОП=007) — связать
         * заявку не с чем; молча писать по адресу 0 нельзя. */
        if (SVS_DEV_TRACE())
            fprintf(sim_deb, "iom%d --- ОТВ не зарегистрирована, заявка@%o не связана\n",
                iom->index, z);
    } else {
        /*
         * Оба поля — АДРЕСА, и АДАП разбирает их в СВОЁМ адресном пространстве
         * (ГАСИПР/ДАЙМА делают ВЧ АДРЕС/ПМА — вычитают СОДЕРЖИМОЕ ячейки,
         * а оно равно базе переноса). Значит строить их надо из ВИРТУАЛЬНОГО
         * адреса заявки, а не из физического: после переноса АДАП-а они
         * расходятся на iom_pvv_base(), и ГАСИПР получает чужой АН.
         *
         * мл16 кодируется как z_virt + база: ДАЙМА вычитает ту же базу
         * (содержимое ПМА ≡ АДРЕС) и получает z_virt. Раньше сюда зашивали
         * A(ПМА)=032102 — адрес ячейки в сборке 2053; в 2253 ячейка на 032073.
         */
        uint32 base = iom_pvv_base(iom);
        uint32 zv = z - base;                   /* заявка в пространстве АДАП-а */
        t_value value48 = ((t_value)(zv - IOM_PVV_BASE) << 17) & BITS48;
        uint32 lo16 = (uint32)(zv + base) & 0177777;
        memory[iom->SQA] = (value48 << 16) | lo16;
        tag[iom->SQA] = TAG_NUMBER48;
    }

    /*
     * ГАСИПР (адап.bemsh) требует, чтобы сл.7 заявки уже нёс признак АКТЗ
     * (М20В'1', "активная заявка") — иначе он трактует это как первую встречу
     * с заявкой, сам взводит АКТЗ и уходит на ОШДВРО (сброс канала), а не на
     * АКТИВ. Настоящий канал взводит этот бит при постановке в очередь
     * завершения; воспроизводим это здесь.
     */
    memory[z + 7] |= ((t_value)IOM_AKTZ) << 16;

    return r;
}

/*
 * Поддержать уровень запроса ПВВ (ГРВП разр.3).
 *
 * Канал взводит разряд, положив заявку в очередь ответов (iom->SQA = ДВРПВВ).
 * АДАП, разобрав заявку в ГАСИПР, обнуляет голову очереди — после этого
 * запрос должен сняться, иначе обработчик ППВВ входит бесконечно.
 */
void iom_update_intr(int cpu_index)
{
    IOMDATA *iom = &iom_data[0];        /* один ПВВ в текущей конфигурации */

    if (iom->SQA != 0 && memory[iom->SQA] == 0 &&
        (cpu_core[cpu_index].GRVP & GRVP_INTR_IOM))
    {
        /*
         * Момент гашения важен: ГЕНС читает ГРВП (РЕГ '247') не сразу, а
         * примерно через 15 команд после входа в ВНЕШПР — сначала упрятываются
         * регистры. Если разряд успевает погаснуть здесь, обработчик видит
         * ГРВП=0, не совпадает ни с Е4/Е8/Е3/Е6 и уходит в СТОП '00301'.
         */
        if (SVS_DEV_TRACE())
            fprintf(sim_deb, "iom%d --- гашу ПРПВВ (ДВРПВВ@%o пуст), PC=%05o\n",
                iom->index, iom->SQA, cpu_core[cpu_index].PC);
        cpu_core[cpu_index].GRVP &= ~GRVP_INTR_IOM;
    }
}

/*
 * ПУСКОБ (КОП=016): обойти очередь ТОЧ и выполнить отложенный обмен.
 *
 * ТОЧ (адрес в iom->IOQA, зарегистрирован командой КОП=006) — таблица очередей,
 * по 2 слова на устройство (НОЧ — начало, КОЧ — конец списка заявок); индекс =
 * 2·НУС (§5.2, КАНСОВ адап.bemsh:2153). Заявка — 8-словный блок (§5.2):
 *   сл.2 ДО  — дескриптор данных (адрес буфера ОП + длина),
 *   сл.3 СО  — управление: ТЕГ48 чтение = разр.39,40,46,48; запись = разр.39,40,
 *   сл.4 СПУ — физический адрес зоны на диске,
 *   сл.5/6 ДР/ДРУ — ответ устройства (заполняем по завершении, младшие 16 разр.),
 *   сл.0 — связь со следующей заявкой (ДАЙМА выделяет адрес).
 *
 * Замечание о конфигурации: в текущем dispak.ini системный диск приходит в
 * ВКЛТОЧ с НУС=0 и уходит по ветви ОТДАЮЗ (заявка кладётся в ТВЗП[НСВС], а не в
 * ТОЧ), поэтому ТОЧ при КОП=016 пуста и этот обход — пока холостой. Чтобы обмен
 * пошёл через ТОЧ, нужна настройка таблиц устройств (НУС≠0) и подключённый диск.
 */
static void iom_pusk_obmen(IOMDATA *iom, int cmd_nus)
{
    uint32 toch = iom->IOQA;
    int nus, found = 0;

    if (toch == 0) {
        if (SVS_DEV_TRACE())
            fprintf(sim_deb, "iom%d --- ПУСКОБ: ТОЧ не зарегистрирована\n", iom->index);
        return;
    }

    /*
     * По 2 слова на устройство, индекс = 2*НУС. НУС — индекс записи в ТУС
     * (см. ПВВ.md §5.3), т.е. от 0 до IOM_TUS_ENTRIES-1. Диск (МД) живёт в
     * блоке класса 5 со смещением 0120 = 80, поэтому обходить надо ВСЮ таблицу:
     * прежняя граница 64 обрывала скан до блока МД, и заявка на диск в ТОЧ
     * оставалась незамеченной ("ТОЧ пуста") при непустой очереди.
     */
    if (! iom_addr_ok(iom, "ТОЧ", toch) || toch + 2*IOM_TUS_ENTRIES >= MEMSIZE)
        return;

    /*
     * По документу (№10.170.002 ТОП, 4.2.1 и 4.4) команда ПОБ НАЗЫВАЕТ
     * устройство: «считывается слово ТУС по адресу БАТУС + НУС, слово ТОЧ по
     * адресу БАТОЧ + 2НУС». Тогда обходить всю таблицу не нужно.
     *
     * Но АДАП этой формой не пользуется: во всех 953 командах ПОБ нашего
     * прогона НУС=0 (слово = КОП|СБ и больше ничего), а работа лежит в ТОЧ[69]
     * (барабан, устр.5) и ТОЧ[81] (диск, устр.1). Нулевой номер по 4.1.2 — не
     * устройство, а служебный блок У ПВВ, так что это именно «просто поищи
     * работу»: в автоматическом режиме (АРВ) канал разбирает очереди сам,
     * без участия ЦП (4.1). Поэтому НУС=0 — обход всей таблицы, ненулевой —
     * ровно одна очередь, как написано в документе.
     */
    if (cmd_nus > 0 && cmd_nus < IOM_TUS_ENTRIES) {
        if (SVS_DEV_TRACE())
            fprintf(sim_deb, "iom%d --- ПУСКОБ: команда назвала НУС=%d,"
                " обслуживаю только эту очередь\n", iom->index, cmd_nus);
    }

    for (nus = (cmd_nus > 0 && cmd_nus < IOM_TUS_ENTRIES) ? cmd_nus : 0;
         nus < IOM_TUS_ENTRIES;
         nus++) {
        t_value head = memory[toch + 2*nus] & BITS48;
        uint32 z;
        int steps = 0;

        if (head == 0)
            continue;

        /*
         * Слот очереди может быть ненулевым, но БЕЗ адреса: поле ДАЙМА
         * (разр.1..15) нулевое. Тогда z вырождается в саму базу ПВВ (0100000),
         * и канал принимает за заявку то, что там лежит, — наблюдались обмены
         * "устр=23/54/55 ЗП зона=0 буфер=0" и звенья, замкнутые сами на себя.
         * Заявки без адреса не существует, слот просто пуст.
         */
        if (IOM_DAIMA(head) == 0)
            continue;

        /*
         * Указатели в ТОЧ и в звеньях заявок хранятся ОТНОСИТЕЛЬНО ПВВ
         * (как и поле АН в ДВРПВВ, §5.5): наблюдалось 01100 при заявке,
         * реально лежащей по 031100. Поэтому базу надо прибавить, иначе
         * обмен пойдёт по мусорному адресу (буфер=0, зона=0).
         */
        /*
         * Указатель в ТОЧ — ОТНОСИТЕЛЬНЫЙ (от ПВВ), поэтому к нему добавляется
         * база ПВВ, а затем — смещение переноса АДАП-а (ячейка АДРЕС), как и
         * для адресов в командных словах БАК. Без второго слагаемого канал
         * берёт заявку по её ВИРТУАЛЬНОМУ адресу (наблюдалось 031100) вместо
         * физического (0101100) и читает нули: направление, зона и буфер
         * получаются нулевыми.
         */
        z = IOM_PVV_BASE + IOM_DAIMA(head) + iom_pvv_base(iom);

        /*
         * Идём по цепочке заявок (связь — 0-е слово).
         *
         * Обход ОБЯЗАН быть ограничен: в памяти встречается звено, чья связь
         * указывает на него же (наблюдалось заявка@100000 при НУС=82), и без
         * ограничителя канал крутится в этом звене вечно. Реальная очередь
         * короче числа записей ТУС, поэтому большего запаса и не нужно.
         */
        while (z != 0 && z + 7 < MEMSIZE && steps < IOM_QUEUE_MAX_STEPS) {
            t_value link = memory[z] & BITS48;
            uint32 next = (link == 0) ? 0 :
                          IOM_PVV_BASE + IOM_DAIMA(link) + iom_pvv_base(iom);

            steps++;
            if (next == z) {
                if (SVS_DEV_TRACE())
                    fprintf(sim_deb, "iom%d --- ТОЧ[%d]: заявка@%o замкнута сама"
                        " на себя, обход прерван\n", iom->index, nus, z);
                next = 0;
            }

            /*
             * nus — индекс записи в ТУС. И класс устройства, и номер внутри
             * класса берём из самой таблицы: раньше здесь вычиталась база МД,
             * и заявка к барабану (НУС=69, класс 4) давала отрицательный номер
             * устройства и бессмысленную зону.
             */
            int unit = 0;
            int devclass = iom_tus_class(iom, nus, &unit);

            if (devclass < 0) {
                /* Один раз на очередь: иначе длинная (или зацикленная)
                 * цепочка заливает трассу гигабайтами одинаковых строк. */
                if (SVS_DEV_TRACE() && steps == 1)
                    fprintf(sim_deb, "iom%d --- ТОЧ[%d]: класс по ТУС не определён"
                        " (ТУС@%o), заявка@%o пропущена\n",
                        iom->index, nus, iom->UTA, z);
                z = next;
                continue;
            }
            found++;
            if (SVS_DEV_TRACE())
                fprintf(sim_deb, "iom%d --- ПУСКОБ: работа найдена в ТОЧ[%d]"
                    " (НУС из команды %d)\n", iom->index, nus, cmd_nus);
            iom_xfer_zaiavka(iom, z, devclass, unit, nus);
            z = next;
        }

        /* Очередь обработана — гасим НОЧ/КОЧ. */
        memory[toch + 2*nus]     = 0;
        memory[toch + 2*nus + 1] = 0;

        if (cmd_nus > 0 && cmd_nus < IOM_TUS_ENTRIES)
            break;                      /* команда назвала устройство — и всё */
    }

    /* Завершение обмена: внешнее прерывание ПРПВВ исходному СВС (ГРВП разр.3). */
    if (found) {
        cpu_core[0].GRVP |= GRVP_INTR_IOM;
        if (SVS_DEV_TRACE())
            fprintf(sim_deb, "iom%d --- ПУСКОБ: обработано заявок %d, ПРПВВ\n",
                iom->index, found);
    } else if (SVS_DEV_TRACE()) {
        fprintf(sim_deb, "iom%d --- ПУСКОБ: ТОЧ@%o пуста "
            "(заявка обслуживается на звонке ЕСВС из ТВЗП, см. iom_service_tvzp)\n",
            iom->index, toch);
    }
}

/*
 * Обслуживание отданной заявки из ТВЗП (ветвь ОТДАЮЗ, НУС=0).
 *
 * Вызывается на звонке РЕГ '50' с признаком ЕСВС ("Запись в ПП"), когда АДАП
 * только что положил заявку в ТВЗП[НСВС] (СЕМБИТ) и сигналит СВС. В реальной СВС
 * заявку дальше обрабатывает монитор СВС; в автономном АДАП этого монитора нет,
 * поэтому ПВВ-канал выполняет обмен сам: читает заявку, переносит данные,
 * проставляет ответ ДР/ДРУ и посылает завершение ПРПВВ.
 */
void iom_service_tvzp(int index)
{
    IOMDATA *iom = &iom_data[index];
    t_value parked = (memory[IOM_TVZP] >> 16) & BITS48;  /* данные в старшей части */
    uint32 z;

    if (!(parked & IOM_SEMBIT))
        return;                             /* заявки в ТВЗП нет */

    z = IOM_DAIMA(parked);
    if (! iom_addr_ok(iom, "заявка из ТВЗП", z) || z + 7 >= MEMSIZE)
        return;
    if (SVS_DEV_TRACE())
        fprintf(sim_deb, "iom%d --- ЕСВС: заявка из ТВЗП@%o → @%o\n",
            iom->index, IOM_TVZP, z);

    /* Устройство берём из НАПРУС (см. комментарий у IOM_NAPRUS), а не из
     * константы: это то же самое слово, которым сконфигурирован обмен. */
    /*
     * Класс устройства определяем по ТУС, как и на пути ПУСКОБ: зашитый
     * IOM_TUS_CLASS_MD отправлял бы заявку к барабану на диск. НУС здесь не
     * приходит отдельным полем (ветка ОТДАЮЗ работает по НУС=0), поэтому
     * берём его из разр.39-42 слова СПУ — того же места, по которому ВЫППВВ
     * сверяет ответ (см. сборку ДР ниже).
     */
    {
        t_value spu = (memory[z + 4] >> 16) & BITS48;
        int nus = (int)((spu >> 38) & 017);
        int unit = 0;
        int devclass = iom_tus_class(iom, nus, &unit);

        if (devclass < 0) {
            /* ТУС не настроена — сохраняем прежнее поведение (диск),
             * иначе загрузка с системного диска перестала бы идти. */
            if (SVS_DEV_TRACE())
                fprintf(sim_deb, "iom%d --- ТВЗП: класс по ТУС не определён"
                    " (НУС=%d), беру МД\n", iom->index, nus);
            devclass = IOM_TUS_CLASS_MD;
            unit = (int)((memory[IOM_NAPRUS] >> 16) & 7);
        } else if (SVS_DEV_TRACE()) {
            fprintf(sim_deb, "iom%d --- ТВЗП: класс %d устр %d по ТУС (НУС=%d)\n",
                iom->index, devclass, unit, nus);
        }
        iom_xfer_zaiavka(iom, z, devclass, unit, nus);
    }

    /* Снимаем СЕМБИТ в слоте ТВЗП — канал освободил заявку (обмен завершён).
     * Данные слова — в старшей части (значение48<<16), поэтому разр.17 значения
     * соответствует разр.33 64-битного слова. */
    memory[IOM_TVZP] &= ~((t_value)IOM_SEMBIT << 16);

    /* Завершение: ПРПВВ исходному СВС (ГРВП разр.3). */
    cpu_core[0].GRVP |= GRVP_INTR_IOM;
}

/*
 * ПОБР: разовый обмен по блоку БВВ, названному прямо в команде.
 *
 * Отличие от ПУСКОБ — никаких очередей: ни ТОЧ, ни ДВР ещё не
 * зарегистрированы (ЦРВ — режим инициализации). Класс устройства взять
 * неоткуда: ТУС тоже нет, поэтому если её нет, считаем устройство диском —
 * загрузчик читает АДАП именно с МД. Номер устройства внутри класса берём из
 * разр.39-42 слова СПУ, как и на пути ПУСКОБ.
 */
static void iom_pobr(IOMDATA *iom, uint32 z, int nus)
{
    int unit = 0, devclass;
    t_value spu;
    t_stat r;

    if (! iom_addr_ok(iom, "БВВ по ПОБР", z) || z + 7 >= MEMSIZE)
        return;

    devclass = iom_tus_class(iom, nus, &unit);
    if (devclass < 0) {
        devclass = IOM_TUS_CLASS_MD;
        spu = (memory[z + 4] >> 16) & BITS48;
        unit = (int)((spu >> 38) & 017);
    }

    if (SVS_DEV_TRACE())
        fprintf(sim_deb, "iom%d --- ПОБР: БВВ@%o класс %d устр %d\n",
            iom->index, z, devclass, unit);

    r = iom_xfer_zaiavka(iom, z, devclass, unit, nus);

    /*
     * Слово состояния по ячейке 0105 (IOM_POBR_STATUS).
     *
     * Формат — дескриптор результата УД из заводской инструкции на УБД
     * (ИБЗ.057.008 ИЭ, «Дескриптор результата», см. responses.md):
     *     разр.0     УСБ  — указатель сбоя, «1» при любой ошибке;
     *     разр.2-5   НУС  — номер внешнего устройства;
     *     разр.8-31  АФСБ — файловый адрес при сбое;
     *     (аппаратный тег слова — битовый набор, TAG_BITSET).
     *
     * ВЫЗПВВ ждёт именно этого: после звонка он читает 0105, маскирует
     * младшие 4 разр. (`и D02377`, 017) и, пока там ноль, уходит на повтор.
     * То есть НУС обязан быть НЕнулевым — номер устройства и есть признак
     * того, что обмен кому-то достался.
     */
    {
        /*
         * Разряды документа считаются по ВСЕМУ 64-разрядному слову, а у нас
         * слово хранится как (значение48<<16)|младшие16. Значит УСБ (разр.0) и
         * НУС (разр.2-5) ложатся в МЛАДШИЕ 16 разр., а не в значение48:
         * команда СЧП кладёт как раз эти младшие 16 разр. в старшую половину
         * РМР, откуда ВЫЗПВВ их и достаёт (`счмр; сда 64+32`).
         *
         * Проверок у ВЫЗПВВ две, и обе сходятся на этой раскладке:
         *   `и D02377` (017) — ответил ли канал вообще (НУС либо УСБ ненулевые);
         *   `и D02400` (разр.33 = разр.1 младшего поля) — это ровно УСБ,
         *      то есть признак неудачи обмена.
         */
        uint32 low = ((uint32)(unit & 017) << 2) | ((r == SCPE_OK) ? 0 : 1);

        memory[IOM_POBR_STATUS] = low;
        tag[IOM_POBR_STATUS] = TAG_BITSET;

        if (SVS_DEV_TRACE())
            fprintf(sim_deb, "iom%d --- ПОБР: состояние@%o младш.16=%06o"
                " (НУС=%d УСБ=%d)\n", iom->index, IOM_POBR_STATUS,
                low, unit & 017, (r == SCPE_OK) ? 0 : 1);
    }

    /* В ЦРВ каждый обмен сопровождается взаимными прерываниями ЦП и ПВВ. */
    cpu_core[0].GRVP |= GRVP_INTR_IOM;
}

/*
 * Запрос от процессора через регистр ПП.
 */
void iom_request(int index)
{
    IOMDATA *iom = &iom_data[index];

    /*
     * Звонок в дверь не несёт адреса. Сначала смотрим в СТБАК (= iom->HA, 0100₈):
     * при инициализации процессор кладёт туда командное слово БАК — указатель на
     * блок БАКПВВ (адрес блока в разр.1..36, КОП в разр.37..44). Значащие 48
     * разрядов — в МЛАДШЕЙ части 64-битного слова (см. описание формата выше).
     */
    t_value ptr = memory[iom->HA] & BITS48;
    if (ptr != 0) {
        int kop = BAK_KOP(ptr);
        uint32 blk = IOM_PHYS(BAK_BLOCK_ADDR(ptr));

        if (SVS_DEV_TRACE())
            fprintf(sim_deb, "iom%d --- СТБАК: КОП=%02o %s СБ=%d НУС=%d"
                " адрес=%o слово=%#jx\n",
                iom->index, kop, bak_kop_name(kop), BAK_SEM(ptr), BAK_NUS(ptr),
                BAK_BLOCK_ADDR(ptr), (uintmax_t)ptr);

        if (kop == BAK_KOP_POBR) {
            /*
             * ПОБР — «пуск объекта разовый» (№10.170.002 ТОП, 4.2.2):
             * «используется при инициализации вычислительного комплекса и
             * может выполняться только в циклическом режиме работы ПВВ (ЦРВ)…
             * Номер устройства; номер канала и адрес блока ввода-вывода
             * задаются непосредственно в полях команды».
             *
             * Так работает первичный загрузчик ВЫЗПВВ: таблиц ТУС/ТОЧ/ДВР ещё
             * нет, он просто кладёт блок БВВ по 070000 и даёт ПОБР с этим
             * адресом. Очередей здесь нет — обслуживаем ровно одну заявку.
             */
            iom_pobr(iom, blk, BAK_NUS(ptr));
            memory[iom->HA] = 0;
            return;
        }

        /* Прочее (в первую очередь ИБАК, КОП=004) — регистрация указателя. */
        iom->BAK = blk;

        /*
         * Подтверждение: гасим СТБАК. Цикл ожидания в процессоре
         * (адап.bemsh:2971: СЧП СТБАК; ПО ДОЖДЛ) выходит, когда старшие 48
         * разрядов слова становятся нулевыми.
         */
        memory[iom->HA] = 0;
        return;
    }

    /*
     * Иначе команда лежит в 2-словном блоке БАКПВВ по запомненному адресу
     * (ЗАПУСК/ПУСКОБ: ЗППР БАКПВВ; РЕГ '50'; затем опрос СЧПР БАКПВВ; ПО ВЫХМКФ,
     * адап.bemsh:3548-3556, 3830-3841).
     */
    if (! iom_addr_ok(iom, "БАКПВВ", iom->BAK))
        return;
    t_value cmd = memory[iom->BAK] & BITS48;
    if (cmd == 0)
        return;

    {
        int kop = BAK_KOP(cmd);

        if (SVS_DEV_TRACE())
            fprintf(sim_deb, "iom%d --- Команда БАКПВВ@%o: КОП=%02o %s"
                " СБ=%d НУС=%d адрес=%o слово=%#jx\n",
                iom->index, iom->BAK, kop, bak_kop_name(kop),
                BAK_SEM(cmd), BAK_NUS(cmd), BAK_BLOCK_ADDR(cmd), (intmax_t)cmd);

        /*
         * Перерегистрация базы — по документу законна («могут быть изменены в
         * процессе работы»), но в середине прогона почти всегда означает, что в
         * БАКПВВ попал мусор: КОП теперь 4-разрядный, и посторонние разряды
         * складываются в ПРАВДОПОДОБНУЮ команду (в трассе — ИДВР адрес=170163
         * после того, как образ ОС лёг поверх АДАП-а). Молча переставлять
         * указатель нельзя — это надо видеть.
         */
        if (kop >= BAK_KOP_REG_UT && kop <= BAK_KOP_REG_ANSW) {
            uint32 was = (kop == BAK_KOP_REG_UT)   ? iom->UTA :
                         (kop == BAK_KOP_REG_TOCH) ? iom->IOQA : iom->SQA;
            uint32 now = IOM_PHYS(BAK_BLOCK_ADDR(cmd));

            if (was != 0 && was != now && SVS_DEV_TRACE())
                fprintf(sim_deb, "iom%d --- ВНИМАНИЕ: %s переставляет базу"
                    " %o -> %o\n", iom->index, bak_kop_name(kop), was, now);
        }

        switch (kop) {
        case BAK_KOP_REG_UT:    /* регистрация таблицы устройств */
            iom->UTA = IOM_PHYS(BAK_BLOCK_ADDR(cmd));
            if (SVS_DEV_TRACE())
                fprintf(sim_deb, "iom%d ---   УТ@%o\n", iom->index, iom->UTA);
            break;

        case BAK_KOP_REG_TOCH:  /* регистрация таблицы очередей ТОЧ */
            iom->IOQA = IOM_PHYS(BAK_BLOCK_ADDR(cmd));
            if (SVS_DEV_TRACE())
                fprintf(sim_deb, "iom%d ---   ТОЧ@%o\n", iom->index, iom->IOQA);
            break;

        case BAK_KOP_REG_ANSW:  /* регистрация таблицы ответов */
            iom->SQA = IOM_PHYS(BAK_BLOCK_ADDR(cmd));
            if (SVS_DEV_TRACE())
                fprintf(sim_deb, "iom%d ---   ОТВ@%o\n", iom->index, iom->SQA);
            break;

        case BAK_KOP_EXCHANGE1: /* обмен (вариант 1): АДАП уже поставил заявку в ТОЧ */
        case BAK_KOP_EXCHANGE3: /* обмен (вариант 3) */
        case BAK_KOP_PUSKOB:    /* ПУСКОБ: пуск обмена по очереди ТОЧ */
            iom_pusk_obmen(iom, BAK_NUS(cmd));
            break;

        default: {
            /*
             * ДИАГНОСТИКА: неизвестный КОП означает, что в БАКПВВ лежит не то,
             * что туда клал АДАП. Проверяем гипотезу "АДАП пишет БАКПВВ по
             * своему виртуальному адресу, а канал читает другую физическую
             * ячейку": печатаем состояние и ищем по памяти слова, похожие на
             * настоящие команды БАК (КОП=004..007 с осмысленным адресом).
             */
            if (SVS_DEV_TRACE()) {
                uint32 a, found = 0;

                fprintf(sim_deb, "iom%d --- ДИАГ БАК: БАКПВВ@%o сл0=%016jo сл1=%016jo"
                    " АДРЕС=%o\n", iom->index, iom->BAK,
                    (uintmax_t)memory[iom->BAK], (uintmax_t)memory[iom->BAK + 1],
                    iom_pvv_base(iom));

                for (a = 1; a < MEMSIZE && found < 12; a++) {
                    t_value w = memory[a] & BITS48;
                    int k = BAK_KOP(w);
                    uint32 blk;

                    if (k < 4 || k > 7)
                        continue;
                    blk = BAK_BLOCK_ADDR(w);
                    if (blk == 0 || blk >= MEMSIZE)
                        continue;
                    fprintf(sim_deb, "iom%d ---   кандидат@%o: КОП=%03o адрес=%o"
                        " (смещение от БАКПВВ %+d)\n",
                        iom->index, a, k, blk, (int)a - (int)iom->BAK);
                    found++;
                }
                if (! found)
                    fprintf(sim_deb, "iom%d ---   команд БАК в памяти не найдено\n",
                        iom->index);
            }
            /*
             * Прочие управляющие команды (МКФ, ППД, сброс канала, реконфигурация) —
             * без передачи данных, только подтверждаем.
             */
            break;
        }
        }
    }

    /*
     * Подтверждение завершения: обнуляем оба слова блока БАКПВВ. Старшие 48 разр.
     * слова 0 → опрос процессора (ПО ВЫХМКФ) выходит; СЕМБИТ снимается, и
     * следующий захват канала (МКФ: И СЕМБИТ; ПО ВЗЯЛМК) проходит.
     */
    memory[iom->BAK]     = 0;
    memory[iom->BAK + 1] = 0;
}
