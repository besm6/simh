PITCH, LEADING, TOP = 6, 13, 9      # ПСТСМВ, СЛСТРК (F'13'), УП := F'9'
STEP_MM = 0.125

# Хвост (КОНТК, pgs.be:1198-1201): два кадра с поднятым пером, X+1023 и
# X+217 - "ПРОТЯЖКА 14,8 СМ".
TRAILER = [0o100, 0o300, 0o077, 0o277, 0o140, 0o100, 0o071, 0o246]


def text_codes(lines):
    """Строки -> коды ГОСТ с 0175 (новая строка) и 0172 (конец)."""
    codes = []
    for n, line in enumerate(lines):
        if n:
            codes.append(NEWLINE)
        for ch in line.upper():
            codes.append(CODE.get(ch, 0o115))
    codes.append(END)
    return codes


def pgs_frames(codes):
    """ПГС (ПРЯЧУ): коды -> байты кадров."""
    out = []
    xp, yp = 0, TOP     # ХП, УП: предыдущая точка в координатах клетки
    col = 0             # КОЛСИМ
    for c in codes:
        if c == END:
            break
        if c == NEWLINE:
            xp += PITCH * col
            yp += LEADING
            col = 0
            continue
        pen = 0         # ЕЩЕСТР: первая точка знака - с поднятым пером
        for x, y in GLYPHS.get(c, GLYPHS[0o115]):
            if x == 7:
                pen = 0                 # НЕРИСУ
                continue
            dy, dx = y - yp, x - xp
            for d, lo, hi in ((dy, 0o100, 0o300), (dx, 0o040, 0o240)):
                a = abs(d)
                out.append(lo | (a & 7) << 2)
                out.append(hi | a >> 3)
            out.append(0o140 | (dy < 0) << 4 | (dx < 0) << 3 | pen)
            xp, yp, pen = x, y, 1
        xp -= PITCH                     # ПСТСМВ: следующая клетка
        col += 1
    return out + TRAILER


def brm(n_x, n_y):
    """РАЗБ: двоичный умножитель частоты; даёт пары (шаг X?, шаг Y?)."""
    bits = max(n_x.bit_length(), n_y.bit_length())
    for n in range(1, 1 << bits):
        j = (n & -n).bit_length() - 1
        b = bits - 1 - j
        sx, sy = n_x >> b & 1, n_y >> b & 1
        if sx or sy:
            yield sx, sy


def gp4_uk(frames):
    """ГП4: байты кадров -> команды УК (по байту на шаг или смену пера)."""
    uk = []
    kadr = None         # [|dx|, |dy|, dx<0, dy<0, перо] собираемого кадра
    penbits = 0o100     # р.7-5 УК: перо поднято

    def flush(k):
        nonlocal penbits
        if k is None:
            return
        dx, dy, sx, sy, pen = k
        if pen is not None:
            new = pen << 4 if pen else 0o100
            if new != penbits:          # НОМЦВ: сначала смена пера
                penbits = new
                uk.append(0o200 | penbits)
        for stx, sty in brm(dx, dy):
            b = 0o200 | penbits
            if sty:
                b |= 0o10 if sy else 0o04
            if stx:
                b |= 0o02 if sx else 0o01
            uk.append(b)

    for byte in frames:
        c, v = byte >> 5, byte & 31
        if c == 2:                      # мл. Y - начало кадра
            flush(kadr)
            kadr = [0, v, 0, 0, None]
        elif kadr is None:
            continue
        elif c == 6:
            kadr[1] |= v << 5
        elif c == 1:
            kadr[0] |= v
        elif c == 5:
            kadr[0] |= v << 5
        elif c == 3:
            kadr[2], kadr[3], kadr[4] = v >> 3 & 1, v >> 4 & 1, v & 3
    flush(kadr)
    uk.append(0o100)                    # КОНЕЦ: двигатель выкл., перо вверх
    return uk


def pen_paths(uk):
    """Исполнение УК: ломаные (в шагах) для участков с опущенным пером."""
    x = y = 0
    paths, cur = [], None
    for b in uk:
        down = b & 0o200 and not b & 0o100 and b & 0o060
        nx = x + (b & 1) - (b >> 1 & 1)
        ny = y + (b >> 2 & 1) - (b >> 3 & 1)
        if down and (nx, ny) != (x, y):
            if cur is None:
                cur = [(x, y)]
                paths.append(cur)
            cur.append((nx, ny))
        elif not down:
            cur = None
        x, y = nx, ny
    return paths


def ps_page(out, num, title, paths, scale):
    pt = STEP_MM * 72 / 25.4 * scale
    xs = [p[0] for path in paths for p in path] or [0]
    ys = [p[1] for path in paths for p in path] or [0]
    out.append("%%Page: {0} {0}\n".format(num))
    out.append("/Helvetica findfont 9 scalefont setfont\n")
    out.append("40 800 moveto ({}) show\n".format(title))
    out.append("gsave 40 780 translate {:.5f} dup scale\n".format(pt))
    out.append("{} {} translate 1 setlinecap 1 setlinejoin "
               "{:.3f} setlinewidth\n".format(-min(xs), -max(ys), 1.2 / pt))
    for path in paths:
        # подряд идущие одинаковые шаги - одним отрезком
        pts = [path[0]]
        for i in range(1, len(path) - 1):
            a, b, c = path[i - 1], path[i], path[i + 1]
            if (b[0] - a[0], b[1] - a[1]) != (c[0] - b[0], c[1] - b[1]):
                pts.append(b)
        pts.append(path[-1])
        out.append("newpath {} {} moveto".format(*pts[0]))
        out.append("".join(" {} {} lineto".format(*p) for p in pts[1:]))
        out.append(" stroke\n")
    out.append("grestore showpage\n")


