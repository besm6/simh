/*
 * Командное слово БАК (см. ПВВ.md §5.6).
 *
 * Процессор (АДАП) строит командное слово в адап.bemsh:2960-2965:
 *   адрес-с-точки-зрения-ПВВ блока БАКПВВ  ИЛИ  КОП,  затем СДА 64+16; ЗПП.
 * Из-за сдвига вправо на 16 перед ЗПП значащие 48 разрядов попадают в МЛАДШУЮ
 * половину 64-битного слова (старшие 16 разрядов нулевые), а не в старшую, как
 * при обычной записи аккумулятора. Слово кладётся в СТБАК (0100₈ = iom->HA),
 * после чего следует звонок в дверь: СЧ ЕПВВ; РЕГ '50' (адап.bemsh:2968-2969).
 *
 *   разряды 1..36   адрес 2-словного блока БАКПВВ с точки зрения ПВВ (физический;
 *                   ДФАПВВ прибавил базу АДРЕС). Здесь же лежат флаги СЕМБИТ
 *                   (разр.17) и ПОБ (разр.21); их выделение — в Phase 2.
 *   разряды 37..44  КОП — код операции (база М36, младший разряд = разряд 37)
 *
 * Пример (наблюдается при ВЫЗОС): слово 0x40000e8040 → КОП=004 (разр.39,
 * чтение/обмен), адрес блока = 0xe8040 = 3500100₈.
 */
/*
 * Раскладка слова БАК по заводскому описанию (№10.170.002 ТОП, 4.2.1-4.2.9;
 * см. ПВВ.md §7Б). Все коды операций перечислены там ТЕТРАДАМИ, поэтому КОП —
 * ровно 4 разряда; прежняя маска 0377 захватывала соседние поля, и посторонние
 * разряды читались как несуществующие команды (в трассе — КОП=027/017/257).
 */
#define BAK_BLOCK_ADDR(v)   ((uint32)((v) & 03777777LL))        /* разр.0..19: адрес */
#define BAK_KOP(v)          ((int)(((v) >> 36) & 017))          /* разр.36..39: КОП */
#define BAK_SEM(v)          ((int)(((v) >> 32) & 1))            /* разр.32: семафорный бит */
#define BAK_NUS(v)          ((int)(((v) >> 54) & 01777))        /* разр.54..63: НУС (до 1024 устр.) */

#define BAK_KOP_EXCHANGE1   001     /* разряд 37 (=М36В'1') — вариант обмена */
#define BAK_KOP_EXCHANGE3   003     /* разряды 37-38 (=М36В'3') — вариант обмена */
#define BAK_KOP_RDEXCHANGE  004     /* разряд 39 (=М36В'4') — чтение/обмен */

/*
 * База пересчёта «адрес АДАП-а → адрес с точки зрения ПВВ».
 *
 * Макрос ДФАПВВ (СЛЦ АДРЕС) прибавляет эту базу к виртуальному адресу; ФАДРЕС
 * считает её из ПРАДАП (после переноса АДАП-а обычно 050000) и кладёт в ячейку
 * АДРЕС. Адрес самой ячейки зависит от сборки АДАП-а (032102 в 2053, 032073 в
 * 2253), поэтому эмулятор её НЕ читает.
 *
 * Вместо этого базу даёт сама инициализация канала: ИБАК регистрирует
 * физический адрес БАКПВВ, а виртуальный БАКПВВ всегда ПВВ+0100 = 030100
 * (СТБАК). Разность — ровно содержимое АДРЕС:
 *   ИБАК адрес=100100  ⇒  база = 100100 − 030100 = 050000.
 */
#define IOM_BAKPVV_VADDR    030100          /* вирт. БАКПВВ = ПВВ + СТБАК */

/*
 * Имена команд ПВВ (№10.170.002 ТОП, 4.2). Нужны в трассе: без них мусор,
 * попавший в БАКПВВ, неотличим от настоящей команды.
 */
static const char *bak_kop_name(int kop)
{
    switch (kop) {
    case 001: return "ПОБ";
    case 002: return "ЗК/ЗРК";
    case 003: return "ОК/ОРК";
    case 004: return "ИБАК";
    case 005: return "ИТУС";
    case 006: return "ИТОЧ";
    case 007: return "ИДВР";
    case 010: return "ГРС";
    case 011: return "ГПС";
    case 012: return "ПОБР";
    case 014: return "ЦРВ";
    case 015: return "АРВ";
    case 016: return "МОП/МКФ";
    default:  return "?";
    }
}

static uint32 iom_pvv_base(IOMDATA *iom)
{
    if (iom->BAK == 0 || iom->BAK < IOM_BAKPVV_VADDR)
        return 0;
    return iom->BAK - IOM_BAKPVV_VADDR;
}

